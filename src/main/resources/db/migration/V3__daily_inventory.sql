-- Daily inventory: reusable product templates, offer status and pickup windows, store time
-- zones and in-app reminders, and the moment an order was collected (for daily figures).

-- Existing stores are in Romania, the only market so far.
alter table store add column time_zone varchar(40) default 'Europe/Bucharest' not null;
alter table store add column reminder_time time;
alter table store add column reminder_dismissed_on date;

create table product_template (
    id                bigint generated by default as identity primary key,
    store_id          bigint                      not null references store (id),
    name              varchar(150)                not null,
    description       varchar(500),
    kind              varchar(20)                 not null,
    original_price    numeric(10, 2)              not null,
    discounted_price  numeric(10, 2)              not null,
    pickup_start      time                        not null,
    pickup_end        time                        not null,
    has_photo         boolean                     not null,
    archived          boolean                     not null,
    created_at        timestamp(6) with time zone not null,
    version           bigint
);
create index idx_product_template_store on product_template (store_id);

create table product_template_photo (
    template_id   bigint      primary key references product_template (id) on delete cascade,
    content_type  varchar(50) not null,
    data          bytea       not null
);

-- Offers published before this migration were all visible, single products without a window.
alter table food_item add column template_id bigint references product_template (id);
alter table food_item add column kind varchar(20) default 'PRODUCT' not null;
alter table food_item add column status varchar(20) default 'ACTIVE' not null;
alter table food_item add column pickup_starts_at timestamp(6) with time zone;
create index idx_food_item_template on food_item (template_id);
create index idx_food_item_store_created on food_item (store_id, created_at);

alter table orders add column picked_up_at timestamp(6) with time zone;
create index idx_orders_picked_up on orders (picked_up_at);
