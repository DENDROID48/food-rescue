-- Rescue Radar: food types, favourites, personal preferences, Web Push subscriptions.

-- Food types chosen by the shop, comma separated (for example "BAKERY,VEGETARIAN").
alter table product_template add column tags varchar(200) default '' not null;
alter table food_item add column tags varchar(200) default '' not null;

create table favourite_store (
    user_id    bigint not null references app_user (id) on delete cascade,
    store_id   bigint not null references store (id) on delete cascade,
    created_at timestamp(6) with time zone not null,
    primary key (user_id, store_id)
);
create index idx_favourite_store_store on favourite_store (store_id);

-- A favourite product follows the shop's saved product, so it works again every day.
create table favourite_product (
    user_id     bigint not null references app_user (id) on delete cascade,
    template_id bigint not null references product_template (id) on delete cascade,
    created_at  timestamp(6) with time zone not null,
    primary key (user_id, template_id)
);
create index idx_favourite_product_template on favourite_product (template_id);

create table radar_profile (
    user_id            bigint primary key references app_user (id) on delete cascade,
    personalised       boolean      not null,
    interests          varchar(200) not null,
    notify_favourites  boolean      not null,
    quiet_start        time,
    quiet_end          time,
    digest_time        time,
    last_digest_on     date,
    time_zone          varchar(40)  not null,
    updated_at         timestamp(6) with time zone not null
);
create index idx_radar_profile_digest on radar_profile (digest_time);

-- What kind of alert a notification is: anti-spam limits count drops and favourites only.
alter table notification add column kind varchar(20) default 'DROP' not null;

create table push_subscription (
    id               bigint generated by default as identity primary key,
    user_id          bigint        not null references app_user (id) on delete cascade,
    endpoint         varchar(1000) not null unique,
    p256dh           varchar(200)  not null,
    auth             varchar(100)  not null,
    created_at       timestamp(6) with time zone not null,
    last_success_at  timestamp(6) with time zone,
    failures         int           not null
);
create index idx_push_subscription_user on push_subscription (user_id);
