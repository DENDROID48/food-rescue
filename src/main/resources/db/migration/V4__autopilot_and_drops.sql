-- Store Autopilot and Rescue Drops: short, instant offers (optionally bundled from leftovers),
-- opt-in drop alerts for customers and an in-app notification inbox.

-- A Rescue Drop is an ordinary offer with a short window that starts the moment it is launched.
alter table food_item add column rescue_drop boolean default false not null;

-- Which leftovers went into a Smart Bundle, so the stock movement can always be traced.
create table bundle_component (
    id              bigint generated by default as identity primary key,
    bundle_item_id  bigint not null references food_item (id),
    source_item_id  bigint not null references food_item (id),
    units           int    not null check (units > 0)
);
create index idx_bundle_component_bundle on bundle_component (bundle_item_id);

-- A customer's opt-in for alerts about drops near a place they chose. No row means no alerts.
create table drop_alert_preference (
    user_id     bigint primary key references app_user (id) on delete cascade,
    enabled     boolean          not null,
    latitude    double precision not null,
    longitude   double precision not null,
    radius_km   double precision not null,
    max_per_day int              not null,
    updated_at  timestamp(6) with time zone not null
);
create index idx_drop_alert_location on drop_alert_preference (latitude, longitude);

create table notification (
    id            bigint generated by default as identity primary key,
    user_id       bigint        not null references app_user (id) on delete cascade,
    store_id      bigint        references store (id),
    food_item_id  bigint        references food_item (id),
    title         varchar(150)  not null,
    body          varchar(300)  not null,
    created_at    timestamp(6) with time zone not null,
    read_at       timestamp(6) with time zone
);
create index idx_notification_user_created on notification (user_id, created_at);
