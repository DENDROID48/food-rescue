-- Account management: language, signing out other devices, account deletion, terms consent and
-- password reset by email.
alter table app_user add column language varchar(5) default 'en' not null;
-- Login tokens issued before this moment are refused (after a password change, a reset or
-- "sign out everywhere").
alter table app_user add column tokens_valid_after timestamp(6) with time zone;
-- Set when the person deletes their account; the row stays, emptied of personal data, so the
-- shops' order history keeps adding up.
alter table app_user add column deleted_at timestamp(6) with time zone;
alter table app_user add column terms_accepted_at timestamp(6) with time zone;

create table password_reset_token (
    id          bigint generated by default as identity primary key,
    user_id     bigint      not null references app_user (id) on delete cascade,
    -- SHA-256 of the token in the emailed link; the token itself is never stored.
    token_hash  varchar(64) not null unique,
    created_at  timestamp(6) with time zone not null,
    expires_at  timestamp(6) with time zone not null,
    used_at     timestamp(6) with time zone
);
create index idx_password_reset_user on password_reset_token (user_id);
