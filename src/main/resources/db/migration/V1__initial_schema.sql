create table app_user (
    id                  bigint generated by default as identity primary key,
    full_name           varchar(120)                not null,
    email               varchar(180)                not null unique,
    password_hash       varchar(100)                not null,
    role                varchar(20)                 not null,
    category            varchar(20)                 not null,
    eligibility_status  varchar(20)                 not null,
    created_at          timestamp(6) with time zone not null
);

create table store (
    id          bigint generated by default as identity primary key,
    name        varchar(150)                not null,
    address     varchar(255)                not null,
    latitude    double precision            not null,
    longitude   double precision            not null,
    active      boolean                     not null,
    owner_id    bigint                      not null references app_user (id),
    created_at  timestamp(6) with time zone not null
);
create index idx_store_location on store (latitude, longitude);
create index idx_store_owner on store (owner_id);

create table food_item (
    id                      bigint generated by default as identity primary key,
    store_id                bigint                      not null references store (id),
    name                    varchar(150)                not null,
    description             varchar(500),
    original_price          numeric(10, 2)              not null,
    discounted_price        numeric(10, 2)              not null,
    quantity_available      integer                     not null,
    pay_it_forward_quantity integer                     not null,
    expires_at              timestamp(6) with time zone not null,
    has_photo               boolean                     not null,
    created_at              timestamp(6) with time zone not null,
    version                 bigint
);
create index idx_food_item_expires_at on food_item (expires_at);
create index idx_food_item_store on food_item (store_id);

create table food_item_photo (
    food_item_id  bigint      primary key references food_item (id) on delete cascade,
    content_type  varchar(50) not null,
    data          bytea       not null
);

create table orders (
    id               bigint generated by default as identity primary key,
    user_id          bigint                      not null references app_user (id),
    food_item_id     bigint                      not null references food_item (id),
    quantity         integer                     not null,
    total_price      numeric(10, 2)              not null,
    type             varchar(20)                 not null,
    status           varchar(20)                 not null,
    pickup_code      varchar(10)                 not null,
    pickup_deadline  timestamp(6) with time zone not null,
    created_at       timestamp(6) with time zone not null,
    version          bigint
);
create index idx_orders_user_created on orders (user_id, created_at);
create index idx_orders_status_deadline on orders (status, pickup_deadline);
create index idx_orders_food_item on orders (food_item_id);
