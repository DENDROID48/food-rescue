package com.foodrescue.domain;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.Instant;

/**
 * A person using the platform: a consumer, a store owner or an administrator.
 *
 * <p>The table is called {@code app_user} because {@code user} is a reserved word in
 * PostgreSQL and in several other databases.</p>
 *
 * <p>Privacy note: the data kept here is deliberately minimal. Details about a person's
 * financial or social situation should never be stored. {@code eligibilityStatus} only records
 * the outcome of the verification, not the reason behind it.</p>
 */
@Entity
@Table(name = "app_user")
@Getter
@Setter
@NoArgsConstructor
public class User {

    /** Surrogate primary key generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, length = 120)
    private String fullName;

    /** Unique login identifier. Uniqueness is enforced by the database, not only in code. */
    @Column(nullable = false, unique = true, length = 180)
    private String email;

    /** BCrypt hash of the password. The password itself is never stored. */
    @Column(nullable = false, length = 100)
    private String passwordHash;

    /** Stored as text (not ordinal) so that reordering the enum never corrupts old rows. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private UserRole role = UserRole.CONSUMER;

    /** Verification for free Pay-It-Forward items; only APPROVED users may claim them. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private EligibilityStatus eligibilityStatus = EligibilityStatus.NOT_REQUESTED;

    @Column(nullable = false, updatable = false)
    private Instant createdAt = Instant.now();

    /** Language of the interface and of emails: en, ro, es, fr, de, it or pt. */
    @Column(nullable = false, length = 5)
    private String language = "en";

    /** Login tokens issued before this moment are refused: after a password change or "sign out everywhere". */
    private Instant tokensValidAfter;

    /** Set when the person deleted their account; the personal data is then already removed. */
    private Instant deletedAt;

    /** When the person agreed to the terms and the privacy policy. */
    private Instant termsAcceptedAt;

    /** Set when an administrator blocked the account: it cannot sign in until unblocked. */
    private Instant blockedAt;

    /** Why it was blocked: a note for other administrators, never shown to the person. */
    @Column(length = 300)
    private String blockedReason;

    /** True when an administrator has verified that this user may receive free items. */
    public boolean isFreeClaimEligible() {
        return eligibilityStatus == EligibilityStatus.APPROVED;
    }
}
